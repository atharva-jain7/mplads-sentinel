headers = {"Authorization": f"Bearer {token}"}

print("\n=== 2. Testing Project List ===")
r_proj = requests.get(f"{BASE}/projects?page=0&size=3", headers=headers)
print("Projects count:", r_proj.json().get("totalElements"))
for p in r_proj.json().get("content", []):
    print(f" - {p['projectId']}: {p['projectName']} [{p['riskLevel']} - {p['riskScore']}]")

print("\n=== 3. Testing Project Details (MPL-10482) ===")
r_det = requests.get(f"{BASE}/projects/MPL-10482", headers=headers)
