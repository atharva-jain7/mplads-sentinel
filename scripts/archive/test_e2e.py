print("Details:", p_det["projectId"], p_det["projectName"])
print(f"Sanctioned: Rs. {p_det['sanctionedAmount']}, Expenditure: Rs. {p_det['expenditureAmount']}, Progress: {p_det['progressPercentage']}%")

print("\n=== 4. Testing Live Pipeline Analysis (POST /analyze) ===")
r_ana = requests.post(f"{BASE}/projects/MPL-10482/analyze", headers=headers)
ana = r_ana.json()
print("Analysis Status:", r_ana.status_code)
print(f"Calculated Risk Score: {ana['riskScore']} / 100 ({ana['riskLevel']})")
print(f"Investigation Priority: {ana['investigationPriority']}")
print("Factors flagged:")
for f in ana.get("factors", []):
    print(f" - [{f['type']} | {f['severity']}]: {f['explanation']}")

print("\n=== 5. Testing Nearby GIS Projects ===")
r_near = requests.get(f"{BASE}/projects/nearby?projectId=MPL-10482&radiusKm=5.0", headers=headers)
